const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { createHash } = require('node:crypto');
const root = path.resolve(__dirname, '..');
const read = name => fs.readFileSync(path.join(root, name));
const original = read('original/Pancake (52).html');
assert.equal(createHash('sha256').update(original).digest('hex'), 'c8eff97d4c0daefd2cf7b6d967a694ce8a999e4a3e1402d88fee4fea6077778c', 'Original version 52 has changed');
const html = original.toString('utf8');
const scripts = [...html.matchAll(/<script\b[^>]*type=["']module["'][^>]*>([\s\S]*?)<\/script>/gi)];
const styles = [...html.matchAll(/<style\b[^>]*>([\s\S]*?)<\/style>/gi)];
assert.equal(scripts.length, 1);
assert.equal(styles.length, 1);
const { applyRenderingFixes } = require('./rendering-fixes.cjs');
const { applyOfficeZoning } = require('./office-zoning.cjs');
const { applyLandmarkPerformance } = require('./landmark-performance.cjs');
assert.deepEqual(read('web/assets/game.bundle.js'), Buffer.from(applyLandmarkPerformance(applyOfficeZoning(applyRenderingFixes(scripts[0][1])))), 'Runtime differs from the reviewed rendering, landmark and Office changes applied to v52');
assert.deepEqual(read('web/assets/game.css'), Buffer.from(styles[0][1] + '\n' + read('web/features/offices.css').toString('utf8')), 'CSS differs from v52 plus the Office tabs');
const shell = read('web/index.html').toString('utf8');
assert.ok(shell.includes('./assets/game.bundle.js') && shell.includes('./assets/game.css'));
assert.ok(shell.includes(read('reference/third-party-notices.txt').toString('utf8').trim()), 'License notices missing');
console.log('PASS: original SHA-256, reviewed rendering/landmark/Office changes, original CSS plus Office tabs, HTML references, and license notices.');
